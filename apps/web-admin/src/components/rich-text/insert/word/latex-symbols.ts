/** Tên hàm không có lệnh sẵn trong KaTeX: phải đi qua `\operatorname`. */
const OPERATOR_NAME_ONLY: Readonly<Record<string, true>> = { arccot: true, cosec: true };

/** Tên hàm → lệnh LaTeX (`\sin`, `\lim`…); tên không có lệnh sẵn thì dùng `\operatorname`. */
export function functionCommand(name: string): string {
  return OPERATOR_NAME_ONLY[name] ? `\\operatorname{${name}}` : `\\${name}`;
}
