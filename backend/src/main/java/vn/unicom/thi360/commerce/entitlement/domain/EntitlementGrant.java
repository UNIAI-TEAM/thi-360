package vn.unicom.thi360.commerce.entitlement.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import vn.unicom.thi360.commerce.spi.GrantSource;

/**
 * One purchase (one exam line of an order) or one compensation attempt (TM 8.5). Benefits, result view,
 * option codes and exam version are the snapshot taken when the grant was made and never change (E21, E25).
 */
@Entity
@Table(name = "entitlement_grant", schema = "commerce")
public class EntitlementGrant {

    @Id
    private UUID id;

    /** Generated by the database while the entitlement row is locked: the FIFO key (E21); grantedAt is display only. */
    @Column(name = "seq", insertable = false, updatable = false)
    private Long seq;

    @Column(name = "entitlement_id", nullable = false, updatable = false)
    private UUID entitlementId;

    @Enumerated(EnumType.STRING)
    @Column(name = "kind", nullable = false, updatable = false)
    private GrantSource kind;

    @Column(name = "order_id", updatable = false)
    private UUID orderId;

    @Column(name = "order_code", updatable = false)
    private String orderCode;

    @Column(name = "exam_id", nullable = false, updatable = false)
    private UUID examId;

    @Column(name = "compensation_attempt_id", updatable = false)
    private UUID compensationAttemptId;

    @JdbcTypeCode(SqlTypes.ARRAY)
    @Column(name = "option_codes", nullable = false, updatable = false, columnDefinition = "text[]")
    private String[] optionCodes;

    @Column(name = "attempts", nullable = false, updatable = false)
    private int attempts;

    @Column(name = "attempts_used", nullable = false)
    private int attemptsUsed;

    @Column(name = "attempts_reserved", nullable = false)
    private int attemptsReserved;

    @Column(name = "attempts_revoked", nullable = false)
    private int attemptsRevoked;

    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "benefits", nullable = false, updatable = false, columnDefinition = "jsonb")
    private Map<String, Object> benefits;

    @Column(name = "result_view", nullable = false, updatable = false)
    private String resultView;

    @Column(name = "exam_version_no", nullable = false, updatable = false)
    private int examVersionNo;

    @Column(name = "granted_at", nullable = false, updatable = false)
    private Instant grantedAt;

    @Column(name = "granted_by", nullable = false, updatable = false)
    private String grantedBy;

    @Column(name = "reason", updatable = false)
    private String reason;

    @Column(name = "revoked_at")
    private Instant revokedAt;

    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    protected EntitlementGrant() {
    }

    private EntitlementGrant(UUID id, UUID entitlementId, GrantSource kind, UUID examId, List<String> optionCodes,
            int attempts, Map<String, Object> benefits, String resultView, int examVersionNo, Instant grantedAt,
            String grantedBy) {
        this.id = id;
        this.entitlementId = entitlementId;
        this.kind = kind;
        this.examId = examId;
        this.optionCodes = optionCodes == null ? new String[0] : optionCodes.toArray(String[]::new);
        this.attempts = attempts;
        this.benefits = benefits == null ? Map.of() : Map.copyOf(benefits);
        this.resultView = resultView;
        this.examVersionNo = examVersionNo;
        this.grantedAt = grantedAt;
        this.grantedBy = grantedBy;
    }

    public static EntitlementGrant purchase(UUID id, UUID entitlementId, UUID orderId, String orderCode, UUID examId,
            List<String> optionCodes, int attempts, Map<String, Object> benefits, String resultView,
            int examVersionNo, Instant grantedAt, String grantedBy) {
        EntitlementGrant grant = new EntitlementGrant(id, entitlementId, GrantSource.PURCHASE, examId, optionCodes,
                attempts, benefits, resultView, examVersionNo, grantedAt, grantedBy);
        grant.orderId = orderId;
        grant.orderCode = orderCode;
        return grant;
    }

    /** One attempt that copies the snapshot of {@code source}, the grant the faulted attempt drew from. */
    public static EntitlementGrant compensation(UUID id, EntitlementGrant source, UUID attemptId, Instant grantedAt,
            String grantedBy, String reason) {
        EntitlementGrant grant = new EntitlementGrant(id, source.entitlementId, GrantSource.COMPENSATION,
                source.examId, source.getOptionCodes(), 1, source.benefits, source.resultView, source.examVersionNo,
                grantedAt, grantedBy);
        grant.compensationAttemptId = attemptId;
        grant.reason = reason;
        return grant;
    }

    public UUID getId() {
        return id;
    }

    public UUID getEntitlementId() {
        return entitlementId;
    }

    public GrantSource getKind() {
        return kind;
    }

    public UUID getOrderId() {
        return orderId;
    }

    public String getOrderCode() {
        return orderCode;
    }

    public UUID getExamId() {
        return examId;
    }

    public UUID getCompensationAttemptId() {
        return compensationAttemptId;
    }

    public List<String> getOptionCodes() {
        return List.of(optionCodes);
    }

    public int getAttempts() {
        return attempts;
    }

    public int getAttemptsUsed() {
        return attemptsUsed;
    }

    public int getAttemptsReserved() {
        return attemptsReserved;
    }

    public int getAttemptsRevoked() {
        return attemptsRevoked;
    }

    public Map<String, Object> getBenefits() {
        return benefits;
    }

    public String getResultView() {
        return resultView;
    }

    public int getExamVersionNo() {
        return examVersionNo;
    }

    public Instant getGrantedAt() {
        return grantedAt;
    }

    public String getGrantedBy() {
        return grantedBy;
    }

    public String getReason() {
        return reason;
    }

    public Instant getRevokedAt() {
        return revokedAt;
    }

    /** True once the whole grant was refunded: its attempts never become usable again. */
    public boolean isRefunded() {
        return revokedAt != null;
    }

    public int attemptsLeft() {
        return attempts - attemptsUsed - attemptsReserved - attemptsRevoked;
    }

    public void reserveOne() {
        attemptsReserved++;
    }

    public void confirmOne() {
        attemptsReserved--;
        attemptsUsed++;
    }

    public void releaseOne() {
        attemptsReserved--;
    }

    /** A reserved attempt handed back on a refunded grant: it is revoked, not usable again. */
    public void releaseOneToRevoked() {
        attemptsReserved--;
        attemptsRevoked++;
    }

    /**
     * Refunds the grant: revokes every attempt neither used nor reserved and marks the grant refunded.
     * Safe to repeat. Returns how many attempts were revoked by this call.
     */
    public int revokeUnused(Instant now) {
        int unused = attemptsLeft();
        attemptsRevoked += unused;
        if (revokedAt == null) {
            revokedAt = now;
        }
        return unused;
    }
}
