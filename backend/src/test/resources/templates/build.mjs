#!/usr/bin/env node
// Generate the migration and the independent expected totals from readable template sources.
// Usage: node backend/src/test/resources/templates/build.mjs <migration-output.sql>
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = dirname(fileURLToPath(import.meta.url));
const output = process.argv[2];
if (!output) throw new Error('Specify the migration output path');

// UUID v5, with the URL namespace and a path including the template code.
function stableId(name) {
  const namespace = Buffer.from('6ba7b8119dad11d80b400c04fd430c8', 'hex');
  const bytes = createHash('sha1').update(namespace).update(name, 'utf8').digest().subarray(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = bytes.toString('hex');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function assignIds(template) {
  // idVersion marks a topology change: ids of a restructured template must differ from the old ones.
  const prefix = template.idVersion ? `${template.code}/${template.idVersion}` : template.code;
  const id = path => stableId(`thi360/exam-template/${prefix}/${path}`);
  function section(section, path) {
    section.id = id(path);
    (section.blocks ?? []).forEach((block, i) => { block.id = id(`${path}/block/${i + 1}`); });
  }
  template.structure.parts.forEach((part, i) => {
    const path = `part/${i + 1}`;
    part.order = i + 1;
    part.id = id(path);
    (part.sections ?? []).forEach((item, j) => section(item, `${path}/section/${j + 1}`));
    (part.subjectPool ?? []).forEach((item, j) => section(item, `${path}/subjectPool/${j + 1}`));
    (part.options ?? []).forEach((option, j) => {
      const optionPath = `${path}/option/${option.code ?? j + 1}`;
      option.id = id(optionPath);
      (option.sections ?? []).forEach((item, k) => section(item, `${optionPath}/section/${k + 1}`));
      (option.blocks ?? []).forEach((block, k) => { block.id = id(`${optionPath}/block/${k + 1}`); });
    });
  });
}

const columns = {
  kind_code: 'kindCode', scope: 'scope', part_code: 'partCode', subject_code: 'subjectCode',
  structure_year: 'structureYear', matrix_year: 'matrixYear', timing: 'timing',
  duration_minutes: 'durationMinutes', max_score: 'maxScore', expert_note: 'expertNote',
  label: 'label', summary: 'summary', build_mode: 'buildMode', is_default: 'isDefault',
  publishable: 'publishable', fixed_counts: 'fixedCounts', fixed_block_counts: 'fixedBlockCounts',
  omitted_locked: 'omittedLocked', structure: 'structure'
};
const sql = value => {
  if (value == null) return 'NULL';
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  if (typeof value === 'object') return `${sql(JSON.stringify(value))}::jsonb`;
  return `'${value.replaceAll("'", "''")}'`;
};

const included = process.env.TEMPLATE_SOURCES?.split(',');
const sources = readdirSync(directory).filter(name =>
  (name.endsWith('.template.json') || name.endsWith('.templates.mjs')) &&
  (!included || included.includes(name))).sort();
// This existing QDA template is not represented in the HQB source; preserve its fixture
// without rewriting its independently maintained migration.
const expected = included ? {} : {
  QDA_PART_MATH: {
    questions: 50, maxPoints: 50, durationMinutes: 80, examKind: 'QDA',
    scope: 'PART', partCode: 'TOAN', subjectCode: null, buildMode: 'STANDARD', isDefault: true
  }
};
// The migration of this change only touches H-SCA and V-SAT; every template still enters
// expected-totals.json, so the fixture covers the complete inventory.
const migrated = new Set(['hsca.templates.mjs', 'vsat.templates.mjs']);
const seenCodes = new Set();
const statements = ['-- Generated by backend/src/test/resources/templates/build.mjs; do not edit by hand.'];
for (const source of sources) {
  const templates = source.endsWith('.json')
    ? [JSON.parse(readFileSync(join(directory, source), 'utf8'))]
    : (await import(new URL(source, import.meta.url))).default;
  for (const entry of templates) {
  const template = structuredClone(entry);
  if (!template.code || seenCodes.has(template.code)) throw new Error(`Missing or duplicate template code in ${source}`);
  seenCodes.add(template.code);
  if (!Array.isArray(template.structure?.parts) || !template.expected) throw new Error(`Incomplete template in ${source}`);
  template.publishable ??= true;
  template.fixedCounts ??= false;
  template.fixedBlockCounts ??= false;
  template.omittedLocked ??= false;
  assignIds(template);
  if (template.buildMode === 'STANDARD') expected[template.code] = {
    questions: template.expected.questions, maxPoints: template.expected.maxPoints,
    durationMinutes: template.durationMinutes, examKind: template.kindCode, scope: template.scope,
    partCode: template.partCode, subjectCode: template.subjectCode,
    buildMode: template.buildMode, isDefault: template.isDefault
  };
  if (!included && !migrated.has(source)) continue;
  const assignments = Object.entries(columns).map(([column, property]) => `${column} = ${sql(template[property])}`);
  if (template.existing) {
    statements.push(`UPDATE exam.exam_template SET\n  ${assignments.join(',\n  ')}\nWHERE code = ${sql(template.code)};`);
  } else {
    const names = ['code', ...Object.keys(columns), 'active'];
    const values = [sql(template.code), ...Object.values(columns).map(property => sql(template[property])), 'true'];
    const updates = Object.keys(columns).map(column => `${column} = EXCLUDED.${column}`);
    statements.push(`INSERT INTO exam.exam_template (${names.join(', ')})\nVALUES (${values.join(', ')})\nON CONFLICT (code) DO UPDATE SET ${updates.join(', ')}, active = true;`);
  }
  }
}
writeFileSync(join(directory, 'expected-totals.json'), `${JSON.stringify(expected, null, 2)}\n`);
writeFileSync(output, `${statements.join('\n\n')}\n`);
